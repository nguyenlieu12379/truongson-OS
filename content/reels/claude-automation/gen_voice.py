"""Voice: Kokoro TTS (free, local), one take per line, joined with set pauses.
Writes sound/voice.wav and timing.js (WORDS = [word, start, end, line], LINES = [start, end]).
Word times inside a line are spread by letter count, so they're close, not exact.
usage: <kokoro venv python> gen_voice.py [voice] [speed]
"""
import json, os, re, sys
import numpy as np, soundfile as sf
from kokoro_onnx import Kokoro

HOME = os.path.expanduser('~/.cache/kokoro')
VOICE = sys.argv[1] if len(sys.argv) > 1 else 'af_heart'
SPEED = float(sys.argv[2]) if len(sys.argv) > 2 else 1.0
START = 0.6   # voice starts after the pop-in
# (line, pause after it in seconds)
LINES = [
    ("Stop using Claude Code like a chatbot.", 0.4),
    ("Here's how to automate properly.", 0.9),
    ("One.", 0.3), ("Pick a task you repeat every week.", 0.3), ("Not your whole job. One task.", 0.9),
    ("Two.", 0.3), ("Write the steps down once, as a skill.", 0.3), ("Claude follows it the same way every time.", 0.9),
    ("Three.", 0.3), ("Give it real tools.", 0.3), ("Connect your apps with MCP, or let it run a script.", 0.9),
    ("Four.", 0.3), ("Make it check its own work.", 0.3), ("Tests, screenshots, a second look.", 0.9),
    ("Five.", 0.3), ("Put it on a trigger.", 0.3), ("A schedule or a hook, so it runs without you.", 1.0),
    ("When it gets something wrong, fix the skill. Not the output.", 0.8),
    ("Comment AUTOMATE and we'll send you the checklist.", 0.0),
]
SAY = {'MCP': 'M C P', 'AUTOMATE': 'automate'}   # what Kokoro reads; captions keep the original word

k = Kokoro(f'{HOME}/kokoro-v1.0.onnx', f'{HOME}/voices-v1.0.bin')
SR = 24000
out, words, lines, t = [np.zeros(int(START * SR), np.float32)], [], [], START
for li, (text, pause) in enumerate(LINES):
    said = ' '.join(SAY.get(w.strip('.,'), w) for w in text.split())
    a, sr = k.create(said, voice=VOICE, speed=SPEED, lang='en-us'); assert sr == SR
    a = a.astype(np.float32)
    env = np.abs(a) > 10 ** (-45 / 20) * np.abs(a).max()
    i0 = max(0, np.argmax(env) - int(0.01 * SR))                       # trim lead-in silence only
    i1 = min(len(a), len(a) - np.argmax(env[::-1]) + int(0.08 * SR))   # keep a natural tail
    a = a[i0:i1]; dur = len(a) / SR
    toks = text.split()
    wts = [len(re.sub(r'[^A-Za-z0-9]', '', w)) + 1.5 + (1.5 if w[-1] in '.,' else 0) for w in toks]
    if 'MCP,' in toks: wts[toks.index('MCP,')] += 2   # spoken as three letters
    c = 0.0
    for w, x in zip(toks, wts):
        s = t + dur * c / sum(wts); c += x; e = t + dur * c / sum(wts)
        words.append([w, round(s, 3), round(e, 3), li])
    lines.append([round(t, 3), round(t + dur, 3)])
    out += [a, np.zeros(int(pause * SR), np.float32)]; t += dur + pause
v = np.concatenate(out); v = v / np.abs(v).max() * 0.89
sf.write('sound/voice.wav', v, SR, subtype='PCM_24')
with open('timing.js', 'w') as f:
    f.write('// generated by gen_voice.py: do not edit by hand\n')
    f.write(f'export const VOICE_END = {t:.3f};\n')
    f.write('export const LINES = ' + json.dumps(lines) + ';\n')
    f.write('export const WORDS = ' + json.dumps(words) + ';\n')
print(f'voice -> sound/voice.wav  {t:.2f} s ({VOICE}, speed {SPEED}), {len(words)} words')
for (s, e), (txt, _) in zip(lines, LINES): print(f'  {s:6.2f}-{e:6.2f}  {txt}')
